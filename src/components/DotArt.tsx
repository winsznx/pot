export function DotArt({ className }: DotArtProps) {
  return (
    <div
      className={className}
      aria-hidden
      style={{
        display: "grid",
        gridTemplateColumns: `repeat(${POT_SHAPE[0].length}, 1fr)`,
        gridTemplateRows: `repeat(${POT_SHAPE.length}, 1fr)`,
        gap: "4px",
      }}
    >
      {POT_SHAPE.flatMap((row, ri) =>
        row.map((cell, ci) => {
          let bg = "transparent";
          if (cell === 1) bg = "var(--color-polar-white)";
          else if (cell === 2) bg = "var(--color-amber-glow)";
          else if (cell === 3) bg = "var(--color-neon-green)";
          return (
            <span
              key={`${ri}-${ci}`}
              style={{
                background: bg,
                borderRadius: "1px",
                aspectRatio: "1 / 1",
                opacity: cell === 0 ? 0 : cell === 1 ? 0.95 : 1,
              }}
            />
          );
        }),
      )}
    </div>
  );
}
